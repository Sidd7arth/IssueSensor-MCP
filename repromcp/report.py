"""Report generation for ReproMCP Visual, separating verified evidence from AI hypotheses."""
from __future__ import annotations

from typing import Any

DISCLAIMER: str = (
    "AI hypothesis—not verified fact. Model-generated observations, causes, and suggestions "
    "are hypotheses and must be verified against actual repository evidence."
)


def render_markdown_report(
    issue_summary: str,
    status: str,
    model_id: str,
    verified_evidence: dict[str, Any],
    ai_analysis: dict[str, Any] | None = None,
    error_message: str = "",
) -> str:
    """Render a comprehensive Markdown report strictly separating verified facts from AI hypotheses.

    Args:
        issue_summary: The reported issue text.
        status: Overall triage status (success, not_configured, api_error, etc.).
        model_id: Name of the AI model.
        verified_evidence: Tool-collected deterministic search matches and test outputs.
        ai_analysis: Parsed output from Gemma (if available).
        error_message: Any error message if AI inference failed or was skipped.

    Returns:
        Formatted GitHub-flavored Markdown document.
    """
    lines: list[str] = [
        "# ReproMCP Visual — Bug Triage Report",
        "",
        f"- **Triage Status:** `{status}`",
        f"- **Model:** `{model_id}`",
        f"- **Screenshot Evaluated:** `{'Yes' if verified_evidence.get('screenshot', {}).get('attached') else 'No'}`",
        "",
        "## Reported Issue",
        f"> {issue_summary.strip()}",
        "",
        "---",
        "",
        "## 1. Verified Repository Evidence (Deterministic Facts)",
        "",
    ]

    # 1. Repository Code Search Evidence
    repo_matches = verified_evidence.get("repository_search", [])
    if repo_matches:
        lines.append(f"### Discovered Code References ({len(repo_matches)} matches)")
        lines.append("")
        for m in repo_matches[:5]:
            f_rel = m.get("file", "unknown")
            l_num = m.get("line", 1)
            lines.append(f"#### `{f_rel}:{l_num}`")
            snippet = m.get("snippet", m.get("text", ""))
            lines.append("```text")
            lines.append(snippet)
            lines.append("```")
            terms = ", ".join(m.get("matched_terms", []))
            lines.append(f"*Matched terms:* {terms}")
            lines.append("")
    else:
        lines.append("### Discovered Code References")
        lines.append("*No relevant source code matches found for the query.*")
        lines.append("")

    # 2. Test Execution Output
    test_info = verified_evidence.get("test_execution", {})
    lines.append("### Safe Test Execution Evidence")
    if test_info:
        test_status = test_info.get("status", "not_run")
        lines.append(f"- **Execution Status:** `{test_status}`")
        if "exit_code" in test_info and test_info["exit_code"] is not None:
            lines.append(f"- **Exit Code:** `{test_info['exit_code']}`")
        if "passed" in test_info:
            lines.append(f"- **Passed:** `{'Yes' if test_info['passed'] else 'No'}`")

        out = (test_info.get("stdout") or test_info.get("stderr") or "").strip()
        if out:
            lines.append("")
            lines.append("```text")
            lines.append(out[-2000:])  # Bound displayed output in report
            lines.append("```")
        elif test_info.get("reason"):
            lines.append(f"*{test_info.get('reason')}*")
    else:
        lines.append("*Test execution was not requested or not run.*")
    lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("## 2. AI Diagnosis & Hypothesis (Gemma 4)")
    lines.append("")
    lines.append(
        "> [!IMPORTANT]\n"
        f"> **Notice:** AI hypothesis—not verified fact. The diagnosis below was generated by `{model_id}`. "
        "File paths, line numbers, and root causes suggested by the AI must be independently verified."
    )
    lines.append("")

    if status == "success" and ai_analysis:
        # Visual observations
        obs = ai_analysis.get("visual_observations", [])
        if obs:
            lines.append("### Visual Observations")
            for item in obs:
                lines.append(f"- {item}")
            lines.append("")

        # Likely root cause & confidence
        conf = ai_analysis.get("confidence", "medium").upper()
        lines.append(f"### Likely Root Cause (Confidence: `{conf}`)")
        lines.append(ai_analysis.get("likely_root_cause", "No cause determined."))
        lines.append("")

        # Reproduction steps
        steps = ai_analysis.get("reproduction_steps", [])
        if steps:
            lines.append("### Reproduction Steps")
            for i, step in enumerate(steps, 1):
                lines.append(f"{i}. {step}")
            lines.append("")

        # Suggested regression test
        reg_test = ai_analysis.get("suggested_regression_test", "")
        if reg_test:
            lines.append("### Suggested Regression Test")
            lines.append("```python")
            lines.append(str(reg_test))
            lines.append("```")
            lines.append("")

        # Unknowns & limitations
        unknowns = ai_analysis.get("unknowns_and_limitations", [])
        if unknowns:
            lines.append("### Unknowns & Limitations")
            for unk in unknowns:
                lines.append(f"- {unk}")
            lines.append("")
    else:
        reason_msg = error_message or f"AI diagnosis status: {status}."
        lines.append(f"### AI Analysis Unavailable")
        lines.append(f"*{reason_msg}*")
        lines.append("")
        lines.append(
            "*Note: Verified repository evidence and test execution results above remain intact and valid.*"
        )
        lines.append("")

    return "\n".join(lines)


def build_triage_report(
    issue_summary: str,
    status: str,
    model_id: str,
    repo_matches: list[dict[str, Any]],
    test_result: dict[str, Any] | None = None,
    screenshot_path: str = "",
    ai_analysis: dict[str, Any] | None = None,
    error_message: str = "",
) -> dict[str, Any]:
    """Assemble the unified structured report dictionary and rendered Markdown."""
    verified_evidence = {
        "repository_search": repo_matches,
        "test_execution": test_result or {"status": "not_requested"},
        "screenshot": {
            "path": screenshot_path,
            "attached": bool(screenshot_path.strip()),
        },
    }

    markdown_doc = render_markdown_report(
        issue_summary=issue_summary,
        status=status,
        model_id=model_id,
        verified_evidence=verified_evidence,
        ai_analysis=ai_analysis,
        error_message=error_message,
    )

    return {
        "status": status,
        "issue_summary": issue_summary,
        "model": model_id,
        "verified_evidence": verified_evidence,
        "ai_analysis": ai_analysis if status == "success" else None,
        "error": error_message if status != "success" else None,
        "disclaimer": DISCLAIMER,
        "rendered_markdown": markdown_doc,
    }
